const assert=require('node:assert/strict');
globalThis.ICLogic=null;
require('../logic.js');
const L=globalThis.ICLogic;
const profile={oreYield:null,oreCycle:null,oreModules:2,iceUnits:null,iceCycle:null,iceModules:2,uptimePct:100,handlingMinutes:12,returnHome:true,observedOreM3Hour:null,observedIceM3Hour:null};
assert.equal(L.miningRate(profile,'ore',5),null);
assert.equal(L.miningRate(profile,'ice',1000),null);
profile.oreYield=120; profile.oreCycle=60;
assert.deepEqual(L.miningRate(profile,'ore',5),{m3Hour:14400,source:'cycle'});
profile.uptimePct=75;
assert.equal(L.miningRate(profile,'ore',5).m3Hour,10800);
profile.observedOreM3Hour=15000;
assert.deepEqual(L.miningRate(profile,'ore',5),{m3Hour:15000,source:'measured'});
profile.iceUnits=1;profile.iceCycle=120;
assert.equal(L.miningRate(profile,'ice',1000).m3Hour,45000);
const full={quote:{gross:120000000,full:true,filled:10000},estimate:{jumps:10,travelMinutes:20,salesTax:9000000,haulCashCost:0,timeCost:2200000}};
const item={volume:50000,units:10000};
const haul={minutesPerJump:2,cashPerJump:0};
const m=L.miningPerformance(item,full,profile,haul,'ore');
assert.equal(m.afterTax,111000000);
assert.equal(m.cashNet,111000000);
assert.equal(m.miningHours,50000/15000);
assert.equal(m.travelMinutes,40); // 20m base + 20m final return
assert.equal(m.handlingMinutes,12);
assert.equal(m.timeHours,50000/15000+52/60);
assert.equal(m.miningIskHour,111000000/(50000/15000));
assert.equal(m.allInIskHour,111000000/m.timeHours);
assert.ok(m.allInIskHour<m.miningIskHour);
const finalReturnOff=L.miningPerformance(item,full,{...profile,returnHome:false},haul,'ore');
assert.equal(finalReturnOff.travelMinutes,20);
assert.ok(finalReturnOff.allInIskHour>m.allInIskHour);
const shipping=L.miningPerformance(item,full,profile,{minutesPerJump:2,cashPerJump:50000},'ore');
assert.equal(shipping.cashNet,m.cashNet-500000);
assert.equal(L.miningPerformance(item,{...full,quote:{...full.quote,full:false}},profile,haul,'ore'),null);
console.log('PASS: blank yield guard, ore/ice yield, uptime, measured preference, all-in cash/time calculation, final return, no double pilot-cost subtraction.');